<?php

require_once __DIR__ . '/pdf_creator.php';

function zt_pdf_artifact_base_dir() {
    return dirname(__DIR__) . '/data/pdf_artifacts';
}

function zt_pdf_artifact_random_token() {
    if (function_exists('random_bytes')) {
        return bin2hex(random_bytes(24));
    }
    if (function_exists('openssl_random_pseudo_bytes')) {
        return bin2hex(openssl_random_pseudo_bytes(24));
    }
    return hash('sha256', uniqid('ztpdf_', true) . mt_rand());
}

function zt_pdf_artifact_is_requested($prompt) {
    $text = strtolower((string) $prompt);
    $has_pdf = preg_match('/\b(pdf|downloadable\s+report|pdf\s+report|report\s+pdf)\b/i', $text);
    $has_doc = preg_match('/\b(report|document|brief|briefing|whitepaper|paper|proposal|case\s+study|research\s+pack)\b/i', $text);
    $has_action = preg_match('/\b(create|make|generate|build|write|draft|produce|export|download|compile|turn|convert|save)\b/i', $text);

    if ($has_pdf && $has_action) {
        return true;
    }
    return (bool) ($has_action && $has_doc && preg_match('/\b(file|download|artifact|for\s+me|for\s+sharing|client-ready|printable)\b/i', $text));
}

function zt_pdf_artifact_wants_web($prompt) {
    return (bool) preg_match('/\b(web|internet|google|search|research|sources|citations|cite|latest|current|today|recent|news|market|price|live|up-to-date|2026)\b/i', (string) $prompt);
}

function zt_pdf_artifact_title_from_reply($reply, $fallback) {
    if (preg_match('/^\s*#\s+(.+)$/m', (string) $reply, $m)) {
        return zt_pdf_clean_text($m[1], 140);
    }
    if (preg_match('/^\s*(?:title|report title)\s*:\s*(.+)$/mi', (string) $reply, $m)) {
        return zt_pdf_clean_text($m[1], 140);
    }
    return zt_pdf_clean_text($fallback, 140);
}

function zt_pdf_artifact_title_from_prompt($prompt) {
    $title = preg_replace('/\b(please|can you|could you|create|make|generate|build|write|draft|produce|export|download|compile|turn|convert|save|pdf|report|document|brief|briefing|whitepaper|paper|proposal|for me|as a|into a|about|on)\b/i', ' ', (string) $prompt);
    $title = trim((string) preg_replace('/\s+/', ' ', $title), " \t\n\r\0\x0B:.-");
    if ($title === '') {
        return 'ZeroThink AI Report';
    }
    $words = preg_split('/\s+/', $title);
    $title = implode(' ', array_slice($words, 0, 12));
    return ucwords(strtolower($title));
}

function zt_pdf_artifact_cleanup($user_dir, $max_age_seconds = 604800) {
    if (!is_dir($user_dir)) {
        return;
    }
    $cutoff = time() - (int) $max_age_seconds;
    foreach (glob($user_dir . '/*') ?: [] as $path) {
        if (is_file($path) && @filemtime($path) < $cutoff) {
            @unlink($path);
        }
    }
}

function zt_pdf_artifact_store($user_id, $title, $body, $meta = []) {
    $user_id = (int) $user_id;
    if ($user_id <= 0) {
        throw new Exception('PDF artifact requires a signed-in user.');
    }
    $body = zt_pdf_clean_text($body, 120000);
    if ($body === '') {
        throw new Exception('PDF artifact body is empty.');
    }

    $base = zt_pdf_artifact_base_dir();
    $user_dir = $base . '/user_' . $user_id;
    if (!is_dir($user_dir) && !mkdir($user_dir, 0700, true)) {
        throw new Exception('Could not create PDF artifact directory.');
    }
    @chmod($base, 0700);
    @chmod($user_dir, 0700);
    @file_put_contents($base . '/.htaccess', "Deny from all\nOptions -Indexes\n");
    @file_put_contents($base . '/index.html', '');
    zt_pdf_artifact_cleanup($user_dir);

    $title = zt_pdf_clean_text($title, 140);
    if ($title === '') {
        $title = 'ZeroThink AI Report';
    }
    $filename = zt_pdf_sanitize_filename($title, 'zerothink-ai-report');
    $token = zt_pdf_artifact_random_token();
    $pdf_path = $user_dir . '/' . $token . '.pdf';
    $meta_path = $user_dir . '/' . $token . '.json';

    $subtitle = isset($meta['subtitle']) ? $meta['subtitle'] : 'Generated by ZeroThink Studio';
    $author = isset($meta['author']) ? $meta['author'] : '';
    $pdf = zt_pdf_create_bytes($title, $body, [
        'subtitle' => $subtitle,
        'author' => $author,
        'footer' => 'ZeroThink AI PDF Artifact',
    ]);

    if (file_put_contents($pdf_path, $pdf, LOCK_EX) === false) {
        throw new Exception('Could not save PDF artifact.');
    }
    @chmod($pdf_path, 0600);

    $expires = time() + 604800;
    $meta_out = [
        'user_id' => $user_id,
        'title' => $title,
        'filename' => $filename,
        'created_at' => gmdate('c'),
        'expires_at' => gmdate('c', $expires),
        'size' => strlen($pdf),
        'provider' => isset($meta['provider']) ? (string) $meta['provider'] : '',
        'model' => isset($meta['model']) ? (string) $meta['model'] : '',
    ];
    file_put_contents($meta_path, json_encode($meta_out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES), LOCK_EX);
    @chmod($meta_path, 0600);

    return [
        'title' => $title,
        'filename' => $filename,
        'url' => '/api_pdf_download.php?t=' . rawurlencode($token),
        'size' => strlen($pdf),
        'expires_at' => $meta_out['expires_at'],
    ];
}

function zt_pdf_artifact_open($user_id, $token) {
    $user_id = (int) $user_id;
    $token = trim((string) $token);
    if ($user_id <= 0 || !preg_match('/^[a-f0-9]{48,64}$/', $token)) {
        return null;
    }
    $user_dir = zt_pdf_artifact_base_dir() . '/user_' . $user_id;
    $pdf_path = $user_dir . '/' . $token . '.pdf';
    $meta_path = $user_dir . '/' . $token . '.json';
    if (!is_file($pdf_path) || !is_file($meta_path)) {
        return null;
    }
    $meta = json_decode((string) file_get_contents($meta_path), true);
    if (!is_array($meta) || (int) (isset($meta['user_id']) ? $meta['user_id'] : 0) !== $user_id) {
        return null;
    }
    $expires_at = strtotime((string) (isset($meta['expires_at']) ? $meta['expires_at'] : ''));
    if ($expires_at > 0 && $expires_at < time()) {
        @unlink($pdf_path);
        @unlink($meta_path);
        return null;
    }
    $meta['path'] = $pdf_path;
    return $meta;
}
